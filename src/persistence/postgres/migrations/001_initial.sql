-- Version 1. Private backend-only storage for PostgreSQL and Supabase.
-- Keep legacy millisecond epochs and JSON strings until the async store cutover.
CREATE SCHEMA IF NOT EXISTS wa_agent;
REVOKE ALL ON SCHEMA wa_agent FROM PUBLIC;

CREATE TABLE IF NOT EXISTS wa_agent.schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS wa_agent.data_imports (
  fingerprint TEXT PRIMARY KEY,
  legacy_brand_id TEXT NOT NULL,
  manifest_json TEXT NOT NULL,
  imported_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wa_agent.chats (
  brand_id TEXT NOT NULL,
  id TEXT NOT NULL,
  name TEXT NOT NULL,
  phone_number TEXT,
  unread_count INTEGER DEFAULT 0,
  last_message TEXT,
  last_timestamp BIGINT,
  is_group SMALLINT DEFAULT 0,
  agent_mode TEXT DEFAULT 'autopilot',
  avatar_url TEXT,
  PRIMARY KEY (brand_id, id)
);
CREATE INDEX IF NOT EXISTS idx_wa_chats_updated ON wa_agent.chats (brand_id, last_timestamp DESC);

CREATE TABLE IF NOT EXISTS wa_agent.messages (
  brand_id TEXT NOT NULL,
  id TEXT NOT NULL,
  chat_id TEXT NOT NULL,
  sender TEXT NOT NULL,
  sender_name TEXT,
  text TEXT NOT NULL,
  timestamp BIGINT NOT NULL,
  is_from_me SMALLINT NOT NULL,
  type TEXT DEFAULT 'text',
  reply_to_id TEXT,
  quoted_json TEXT,
  reactions_json TEXT,
  transcription TEXT,
  status TEXT DEFAULT 'sent',
  PRIMARY KEY (brand_id, id)
);
CREATE INDEX IF NOT EXISTS idx_wa_messages_chat_time ON wa_agent.messages (brand_id, chat_id, timestamp DESC, id);

CREATE TABLE IF NOT EXISTS wa_agent.contact_dossiers (
  brand_id TEXT NOT NULL,
  chat_id TEXT NOT NULL,
  name TEXT NOT NULL,
  phone TEXT,
  stage TEXT DEFAULT 'lead',
  facts_json TEXT DEFAULT '[]',
  commitments_json TEXT DEFAULT '[]',
  preferred_tone TEXT,
  notes TEXT,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (brand_id, chat_id)
);

CREATE TABLE IF NOT EXISTS wa_agent.drafts (
  brand_id TEXT NOT NULL,
  id TEXT NOT NULL,
  chat_id TEXT NOT NULL,
  incoming_message_id TEXT NOT NULL,
  incoming_text TEXT NOT NULL,
  proposed_reply TEXT NOT NULL,
  reasoning TEXT NOT NULL,
  confidence DOUBLE PRECISION NOT NULL,
  status TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (brand_id, id)
);
CREATE INDEX IF NOT EXISTS idx_wa_drafts_pending ON wa_agent.drafts (brand_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS wa_agent.contact_memories (
  id TEXT PRIMARY KEY,
  brand_id TEXT NOT NULL,
  jid TEXT NOT NULL,
  content TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wa_contact_memories_jid ON wa_agent.contact_memories (brand_id, jid, created_at);

CREATE TABLE IF NOT EXISTS wa_agent.brand_sources (
  source_id TEXT PRIMARY KEY,
  brand_id TEXT NOT NULL,
  type TEXT NOT NULL,
  locator TEXT NOT NULL,
  authority TEXT NOT NULL,
  locale TEXT,
  retired SMALLINT NOT NULL DEFAULT 0,
  UNIQUE (brand_id, type, locator)
);
CREATE INDEX IF NOT EXISTS idx_wa_brand_sources_active ON wa_agent.brand_sources (brand_id, retired);

CREATE TABLE IF NOT EXISTS wa_agent.brand_source_versions (
  version_id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL REFERENCES wa_agent.brand_sources(source_id),
  hash TEXT NOT NULL,
  "current" SMALLINT NOT NULL,
  last_checked BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wa_brand_versions_current ON wa_agent.brand_source_versions (source_id, "current");

CREATE TABLE IF NOT EXISTS wa_agent.knowledge_chunks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id TEXT NOT NULL,
  version_id TEXT NOT NULL,
  content TEXT NOT NULL,
  location TEXT NOT NULL,
  embedding_json TEXT
);
CREATE INDEX IF NOT EXISTS idx_wa_knowledge_scope ON wa_agent.knowledge_chunks (source_id, version_id);
CREATE INDEX IF NOT EXISTS idx_wa_knowledge_lexical ON wa_agent.knowledge_chunks USING GIN (to_tsvector('simple', content));

CREATE TABLE IF NOT EXISTS wa_agent.agent_workflows (
  workflow_id TEXT PRIMARY KEY,
  brand_id TEXT NOT NULL,
  contact_id TEXT NOT NULL,
  goal TEXT NOT NULL,
  state TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wa_workflow_brand ON wa_agent.agent_workflows (brand_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS wa_agent.agent_tool_runs (
  brand_id TEXT NOT NULL,
  "key" TEXT NOT NULL,
  workflow_id TEXT NOT NULL,
  tool_name TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  status TEXT NOT NULL,
  output_json TEXT,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (brand_id, "key")
);
CREATE INDEX IF NOT EXISTS idx_wa_tool_runs_workflow ON wa_agent.agent_tool_runs (brand_id, workflow_id);

CREATE TABLE IF NOT EXISTS wa_agent.brand_sheet_connectors (
  brand_id TEXT PRIMARY KEY,
  sheet_id TEXT NOT NULL,
  gid TEXT,
  enabled SMALLINT NOT NULL DEFAULT 1,
  updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS wa_agent.customer_facts (
  brand_id TEXT NOT NULL,
  contact_id TEXT NOT NULL,
  "key" TEXT NOT NULL,
  "value" TEXT NOT NULL,
  source_message_id TEXT NOT NULL,
  confidence DOUBLE PRECISION NOT NULL,
  verified_at BIGINT NOT NULL,
  expires_at BIGINT,
  PRIMARY KEY (brand_id, contact_id, "key")
);
CREATE INDEX IF NOT EXISTS idx_wa_customer_facts_expiry ON wa_agent.customer_facts (brand_id, contact_id, expires_at);

CREATE TABLE IF NOT EXISTS wa_agent.customer_cases (
  case_id TEXT PRIMARY KEY,
  brand_id TEXT NOT NULL,
  contact_id TEXT NOT NULL,
  intent TEXT NOT NULL,
  source_message_id TEXT NOT NULL,
  status TEXT NOT NULL,
  provider_receipt_id TEXT,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wa_cases_customer ON wa_agent.customer_cases (brand_id, contact_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS wa_agent.engagement_triggers (
  trigger_id TEXT PRIMARY KEY,
  brand_id TEXT NOT NULL,
  contact_id TEXT NOT NULL,
  reason TEXT NOT NULL,
  due_at BIGINT NOT NULL,
  source_workflow_id TEXT NOT NULL,
  consent_ref TEXT,
  template_ref TEXT,
  status TEXT NOT NULL,
  receipt_id TEXT,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_wa_followup_due ON wa_agent.engagement_triggers (status, due_at);
CREATE INDEX IF NOT EXISTS idx_wa_followup_brand_contact ON wa_agent.engagement_triggers (brand_id, contact_id, status);

CREATE TABLE IF NOT EXISTS wa_agent.engagement_optouts (
  brand_id TEXT NOT NULL,
  contact_id TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (brand_id, contact_id)
);

CREATE TABLE IF NOT EXISTS wa_agent.agent_evaluations (
  brand_id TEXT NOT NULL,
  scenario_id TEXT NOT NULL,
  intent TEXT NOT NULL,
  resolved SMALLINT NOT NULL,
  supported SMALLINT NOT NULL,
  missing_source TEXT,
  question_hash TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (brand_id, scenario_id)
);
CREATE INDEX IF NOT EXISTS idx_wa_evaluation_gaps ON wa_agent.agent_evaluations (brand_id, intent, missing_source);
